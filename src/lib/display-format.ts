/**
 * Shows a fraction such as "0.1" or 0.0275 as a percentage ("10%", "2.75%").
 * Rounds away floating-point noise (0.07 * 100 = 7.000000000000001).
 * Returns the fallback for missing or non-numeric input.
 */
export function formatFractionAsPercent(
  value: unknown,
  fallback = "—",
): string {
  if (value === null || value === undefined || value === "") return fallback;
  const fraction = typeof value === "number" ? value : Number(value);
  if (!Number.isFinite(fraction)) return fallback;
  const percent = Number((fraction * 100).toFixed(6));
  return `${percent}%`;
}

/**
 * Upstream data keys that carry spelling mistakes. The JSON is regenerated by
 * the data uploader, so the labels are corrected here instead of in the file.
 */
const LABEL_FIXES: Record<string, string> = {
  Pipline_length: "Pipeline length",
  Unbonding_lenth: "Unbonding length",
};

/** Turns a data key such as "Min_epoch_duration" into a readable label. */
export function parameterLabel(key: string): string {
  return LABEL_FIXES[key] ?? key.replace(/_/g, " ");
}
